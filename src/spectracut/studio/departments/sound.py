VOICEOVER = "voiceover"
SOUND_DESIGN = "sound_design"
MUSIC = "music"
MIX = "mix"

TEMP_VO = "temp-vo"
"""Mark on a voiceover made by the local TTS model; delivery flags it (#252)."""
DELIVERY: Literal["streaming"] = "streaming"
DEFAULT_VOICE = "narrator"
END_CARD_MARKERS = ("end-card", "end_card", "endcard")
"""Edit marker names that mark where the end card starts."""
_FALLBACK_CHARS_PER_S = 15.0
FOLEY_CANDIDATES = 1
"""Each foley candidate is a full video-to-audio pass on the model host, so one each."""

ELEVENLABS = Provenance(
    source="generated",
    origin="elevenlabs",
    licence="ElevenLabs commercial terms",
    commercial=True,
)
LOCAL_TTS = Provenance(
    source="generated",
    origin="local-tts",
    licence="temp VO, not for delivery",
    commercial=False,
)


# ------------------------------------------------------------------- outputs


class SoundDesignCue(StrictModel):
    cue_id: Slug
    layer_id: Slug
    frame: int
    """Edit frame the cue starts on (its event frame plus offset)."""
    media_ref: str = Field(min_length=1)
    provenance: Provenance


class SoundDesign(StrictModel):
    """The FX cues as an :class:`AudioRecipe` and the generated file of each layer."""

    recipe: AudioRecipe
    cues: list[SoundDesignCue] = Field(default_factory=list)


class MusicBed(StrictModel):
    """A music bed cut to the edit: its file, length, end card and edit plan."""

    media_ref: str = Field(min_length=1)
    duration_s: float = Field(gt=0.0)
    end_card_s: float = Field(ge=0.0)
    plan_hash: str = Field(min_length=1)
    provenance: Provenance
    beats_s: list[float] = Field(default_factory=list)
    """Beat times on the cut score (seconds from its start), for cutting on the beat."""
    tempo_bpm: float | None = None
    """The cut score's tempo: the source tempo over the plan's stretch ratio."""


class Mix(StrictModel):
    """The master and its stems, with the audio QA rows of the master."""

    master: str = Field(min_length=1)
    stems: dict[Literal["dx", "mx", "fx"], str]
    loudness_lufs: float | None
    true_peak_dbtp: float | None
    qa: list[QACheck]
    delivery: Literal["streaming"] = DELIVERY


def is_temp_vo(output: JsonValue | BaseModel) -> bool:
    """Whether a voiceover output is temp VO that must not ship (delivery, #252)."""
    track = output if isinstance(output, VoiceoverTrack) else VoiceoverTrack.model_validate(output)
    return track.temp_vo or track.mark == TEMP_VO


# --------------------------------------------------------------- departments


class Voiceover(Department):
    """Voices the script: ElevenLabs final VO when configured, else local temp VO."""

    name = "voiceover"
    produces = frozenset({VOICEOVER})
    inputs: ClassVar[dict[str, type[BaseModel]]] = {SCRIPT: Script}
    output = VoiceoverTrack
    skill_pack = SKILLS_ROOT / "sound-designer"
    # The ElevenLabs projection scales with the script; estimate.py supplies it.
    cost = CostEstimate()


class SoundDesigner(Department):
    """A locally generated cue on every cut, transition and ramp of the edit."""

    name = "sound-designer"
    produces = frozenset({SOUND_DESIGN})
    inputs: ClassVar[dict[str, type[BaseModel]]] = {ANIMATIC: Edit}
    output = SoundDesign
    cost = CostEstimate(gpu_minutes=4.0)


class Composer(Department):
    """A locally generated music bed conformed to the edit."""

    name = "composer"
    produces = frozenset({MUSIC})
    inputs: ClassVar[dict[str, type[BaseModel]]] = {ANIMATIC: Edit}
    output = MusicBed
    skill_pack = SKILLS_ROOT / "sound-designer"
    cost = CostEstimate(gpu_minutes=3.0)


class Mixer(Department):
    """Stems and a loudness-checked master."""

    name = "mixer"
    produces = frozenset({MIX})
    inputs: ClassVar[dict[str, type[BaseModel]]] = {
        ANIMATIC: Edit,
        VOICEOVER: VoiceoverTrack,
        SOUND_DESIGN: SoundDesign,
        MUSIC: MusicBed,
    }
    output = Mix
    cost = CostEstimate()


SOUND_DEPARTMENTS: tuple[type[Department], ...] = (Voiceover, SoundDesigner, Composer, Mixer)


def sound_nodes(script_id: str = SCRIPT, timing_id: str = ANIMATIC) -> list[NodeSpec]:
    """The four sound nodes; sound design, music and mix follow ``timing_id``'s edit."""
    return [
        NodeSpec(id=VOICEOVER, kind=VOICEOVER, department=Voiceover.name, inputs=(script_id,)),
        NodeSpec(
            id=SOUND_DESIGN, kind=SOUND_DESIGN, department=SoundDesigner.name, inputs=(timing_id,)
        ),
        NodeSpec(id=MUSIC, kind=MUSIC, department=Composer.name, inputs=(timing_id,)),
        NodeSpec(
            id=MIX,
            kind=MIX,
            department=Mixer.name,
            inputs=(timing_id, VOICEOVER, SOUND_DESIGN, MUSIC),
        ),
    ]


def elevenlabs_configured() -> bool:
    """``ELEVENLABS_API_KEY`` is set, or providers run in mock mode."""
    return bool(os.environ.get(ELEVENLABS_ENV_VAR, "").strip()) or mock_mode()


# -------------------------------------------------------------------- runner


class SoundRunner:
    """Builds the sound nodes in code; other kinds pass through to ``inner``.

    ``voice_over`` defaults to a :class:`VoiceOver` caching under ``workdir/vo``;
    ``runtime``/``providers`` reach the local models (``generate_scene``); ``ardour``
    renders the mix; ``stretcher`` fits the music; ``clock`` meters local model time.
    ``picture`` renders a clip of the edit to a movie for foley; ``None`` means no foley.
    """

    def __init__(
        self,
        inner: Runner,
        departments: Mapping[str, type[Department]],
        *,
        workdir: Path,
        voice_over: VoiceOver | None = None,
        elevenlabs_configured: Callable[[], bool] = elevenlabs_configured,
        runtime: ModelRuntime | None = None,
        runtime_problem: str | None = None,
        providers: Mapping[str, LocalProvider] | None = None,
        ardour: ArdourRunner | None = None,
        stretcher: Stretcher | None = None,
        clock: Callable[[], float] = time.monotonic,
        picture: AnimaticPreview | None = None,
    ) -> None:
        self.inner = inner
        self.departments = departments
        self.workdir = Path(workdir)
        self.voice_over = voice_over
        self.elevenlabs_configured = elevenlabs_configured
        self.runtime = runtime
        self.runtime_problem = runtime_problem
        self.providers = providers
        self.ardour = ardour
        self.stretcher = stretcher
        self.clock = clock
        self.picture = picture

    def __call__(self, ctx: RunContext) -> RunResult:
        build = {
            VOICEOVER: self._voiceover,
            SOUND_DESIGN: self._sound_design,
            MUSIC: self._music,
            MIX: self._mix,
        }.get(ctx.spec.kind)
        return build(ctx) if build is not None else self.inner(ctx)

    def _done(self, ctx: RunContext, output: BaseModel, usage: Usage) -> RunResult:
        dept = self.departments[ctx.spec.department]
        return RunResult(
            output=dept.validate_output(ctx.spec.id, output.model_dump(mode="json")), usage=usage
        )

    def _minutes(self, start: float) -> float:
        return max(0.0, self.clock() - start) / 60.0

    def _need_models(self, ctx: RunContext) -> None:
        """Fail before any local model runs when there is no way to reach one.

        The error carries ``runtime_problem``, which names the model host and how to
        register it, instead of the provider registry's generic one.
        """
        if self.runtime is None and self.providers is None and not mock_mode():
            problem = self.runtime_problem or "no model runtime (no model host configured)"
            raise ProviderError("local", f"{ctx.spec.kind}: {problem}")

    def _edit(self, ctx: RunContext) -> Edit:
        return Edit.model_validate(ctx.inputs[ctx.spec.inputs[0]])

    # ---- voiceover

    def _voiceover(self, ctx: RunContext) -> RunResult:
        script = Script.model_validate(ctx.inputs[ctx.spec.inputs[0]])
        voiced = [line for line in script.lines if line.vo.strip()]
        lines = [VoLine(id=f"line-{n}", text=line.vo) for n, line in enumerate(voiced)]
        final = self.elevenlabs_configured()
        if not final and self.voice_over is None and lines:
            self._need_models(ctx)
        vo = self.voice_over or VoiceOver(
            self.workdir / "vo",
            voice=DEFAULT_VOICE,
            local=None if final else LocalTts(runtime=self.runtime),
        )
        usage = Usage()
        if final:
            # An accepted script input is a locked script (the graph only passes
            # accepted outputs), so final VO may run.
            result = vo.final(lines, script_locked=True)
            paths, usage = result.paths, result.usage
        else:
            start = self.clock()
            paths = vo.temp(lines)
            usage = Usage(gpu_minutes=self._minutes(start))
        track = VoiceoverTrack(
            lines=[
                VoiceoverLine(
                    id=vl.id,
                    beat=line.beat,
                    text=vl.text,
                    media_ref=str(paths[vl.id]),
                    duration_s=_duration(paths[vl.id], vl.text),
                )
                for vl, line in zip(lines, voiced, strict=True)
            ],
            provider="elevenlabs" if final else "local",
            temp_vo=not final,
            mark=None if final else TEMP_VO,
        )
        return self._done(ctx, track, usage)

    # ---- sound design

    def _sound_design(self, ctx: RunContext) -> RunResult:
        edit = self._edit(ctx)
        planned = cue_recipe(edit, edit_events(edit), "sound-design")
        requests: list[CueRequest] = []
        for cue in planned.cues:
            event = cue.id.rsplit("-", 1)[0]
            for layer in cue.layers:
                requests.append(
                    CueRequest(
                        cue_id=f"{cue.id}.{layer.id}",
                        kind="sfx",
                        description=f"{layer.sound.kind} layer of a {event} in a product film",
                        duration_s=layer.sound.duration_seconds,
                        seed=layer.sound.seed,
                    )
                )
        foley_cues, foley = self._foley(edit, planned)
        if requests or foley:
            self._need_models(ctx)
        start = self.clock()
        chosen = {
            s.cue_id: s
            for s in generate_scene(
                requests,
                self.workdir / "sound_design",
                runtime=self.runtime,
                providers=self.providers,
            )
        }
        if foley:
            chosen |= {
                s.cue_id: s
                for s in generate_scene(
                    foley,
                    self.workdir / "sound_design",
                    runtime=self.runtime,
                    providers=self.providers,
                    candidates=FOLEY_CANDIDATES,
                )
            }
        minutes = self._minutes(start) if requests or foley else 0.0
        cues: list[Cue] = []
        rows: list[SoundDesignCue] = []
        for cue in [*planned.cues, *foley_cues]:
            layers = []
            for layer in cue.layers:
                pick = chosen[f"{cue.id}.{layer.id}"]
                layers.append(layer.model_copy(update={"sound": pick.spec}))
                rows.append(
                    SoundDesignCue(
                        cue_id=cue.id,
                        layer_id=layer.id,
                        frame=(cue.frame or 0) + cue.offset_frames,
                        media_ref=str(pick.path),
                        provenance=pick.spec.provenance,
                    )
                )
            cues.append(cue.model_copy(update={"layers": layers}))
        recipe = planned.model_copy(update={"cues": cues})
        place_cues(recipe, edit)  # every cue lands inside the edit, sample-accurately
        return self._done(ctx, SoundDesign(recipe=recipe, cues=rows), Usage(gpu_minutes=minutes))

    def _foley(self, edit: Edit, planned: AudioRecipe) -> tuple[list[Cue], list[CueRequest]]:
        """One foley cue per picture clip with real media, and the request for each.

        Each clip is rendered alone (``picture``) to ``sound_design/picture/<clip>.mp4``
        and the foley model hears that movie. No ``picture`` renderer means no foley.
        """
        track = _picture_track(edit)
        if self.picture is None or track is None:
            return [], []
        cues: list[Cue] = []
        requests: list[CueRequest] = []
        for clip in track.clips():
            if clip.nested is not None or not Path(clip.media_ref).is_file():
                continue  # placeholder boards (``board:<id>``) have no picture to hear
            frame = track.record_start(clip.id)
            start = planned.frame_sample(frame)
            room = (planned.duration_samples - start) / planned.sample_rate
            seconds = min(float(edit.rate.seconds(clip.duration)), room)
            if seconds <= 0:
                continue
            movie = self.workdir / "sound_design" / "picture" / f"{clip.id}.mp4"
            movie.parent.mkdir(parents=True, exist_ok=True)
            alone = Edit(
                id=edit.id,
                rate=edit.rate,
                tracks=[Track(id="picture", kind="video", items=[clip.model_copy()])],
            )
            movie = Path(self.picture(alone, movie))
            seed = zlib.crc32(f"{clip.id}:{frame}".encode())
            sound = SoundSpec(
                kind="foley", duration_seconds=seconds, seed=seed, provenance=PROCEDURAL
            )
            cue_id = f"foley-{clip.id}"
            cues.append(
                Cue(id=cue_id, bus="fx", frame=frame, layers=[Layer(id="body", sound=sound)])
            )
            requests.append(
                CueRequest(
                    cue_id=f"{cue_id}.body",
                    kind="foley",
                    description=f"foley of shot {clip.shot_id or clip.id} in a product film",
                    duration_s=seconds,
                    video_path=movie,
                    seed=seed,
                )
            )
        return cues, requests

    # ---- music

    def _music(self, ctx: RunContext) -> RunResult:
        edit = self._edit(ctx)
        if edit.duration <= 0:
            raise ValueError(f"edit {edit.id!r} is empty")
        target = float(edit.seconds)
        request = CueRequest(
            cue_id="score",
            kind="music",
            description=f"music bed for the product film {edit.name or edit.id}",
            duration_s=target,
        )
        self._need_models(ctx)
        start = self.clock()
        (bed,) = generate_scene(
            [request], self.workdir / "music", runtime=self.runtime, providers=self.providers
        )
        minutes = self._minutes(start)
        end_card = _end_card_s(edit)
        grid = analyze(bed.path)
        plan = plan_edit(grid, target_s=target, end_card_s=end_card, fps=float(edit.rate))
        out = render_edit(
            plan, bed.path, self.workdir / "music" / "score.wav", stretcher=self.stretcher
        )
        _fit_length(out, target)
        music = MusicBed(
            media_ref=str(out),
            duration_s=target,
            end_card_s=plan.hit_out_s,
            plan_hash=plan.content_hash(),
            provenance=edited_sound(plan, bed.spec.provenance).provenance,
            beats_s=list(cut_beats(plan, grid)),
            tempo_bpm=grid.tempo_bpm / plan.ratio if plan.ratio > 0 else None,
        )
        return self._done(ctx, music, Usage(gpu_minutes=minutes))

    # ---- mix

    def _mix(self, ctx: RunContext) -> RunResult:
        edit = self._edit(ctx)
        vo = VoiceoverTrack.model_validate(ctx.inputs[VOICEOVER])
        design = SoundDesign.model_validate(ctx.inputs[SOUND_DESIGN])
        # Profiles without a music stage (standard) mix dialogue and effects only.
        bed = ctx.inputs.get(MUSIC)
        music = MusicBed.model_validate(bed) if bed is not None else None
        recipe, files = mix_recipe(edit, vo, design, music)
        selections = [_file_selection(spec, path) for spec, path in files]
        result = render_mix(
            recipe,
            edit,
            self.workdir / "mix",
            generator=GenerativeSoundGenerator(selections),
            runner=self.ardour,
        )
        qa = check_audio(result.master, DELIVERY)
        try:
            _, channels = read_wav(result.master)
            qa.append(check_clipping(channels))
        except (OSError, ValueError) as exc:
            qa.append(QACheck(name="audio.clipping", status="fail", detail=str(exc)))
        failing = [
            row
            for row in qa
            if row.status == "fail"
            and row.name in ("audio.read", "audio.loudness", "audio.true_peak")
        ]
        if failing:
            raise ValueError(
                "mix fails audio QA: "
                + "; ".join(f"{r.name}={r.value} ({r.detail})" for r in failing)
            )
        values = {row.name: row.value for row in qa}
        mix = Mix(
            master=str(result.master),
            stems={bus: str(path) for bus, path in result.stems.items()},
            loudness_lufs=values.get("audio.loudness"),
            true_peak_dbtp=values.get("audio.true_peak"),
            qa=qa,
        )
        return self._done(ctx, mix, Usage())


# ------------------------------------------------------------------- helpers


def mix_recipe(
    edit: Edit, vo: VoiceoverTrack, design: SoundDesign, music: MusicBed | None
) -> tuple[AudioRecipe, list[tuple[SoundSpec, Path]]]:
    """The mix of ``edit``: DX from the VO lines, MX from the bed (none when ``music``
    is ``None``), FX from sound design.

    Returns the recipe and the file behind every sound in it.
    """
    shell = AudioRecipe(
        id="mix",
        sample_rate=design.recipe.sample_rate,
        rate=edit.rate,
        duration_frames=edit.duration,
    )
    cues: list[Cue] = []
    files: list[tuple[SoundSpec, Path]] = []

    def add(cue_id: str, bus: Literal["dx", "mx"], frame: int, ref: str, spec: SoundSpec) -> None:
        room = (shell.duration_samples - shell.frame_sample(frame) - 1) / shell.sample_rate
        if room <= 0:
            return
        if spec.duration_seconds > room:
            spec = spec.model_copy(update={"duration_seconds": room})
        cues.append(Cue(id=cue_id, bus=bus, frame=frame, layers=[Layer(id="main", sound=spec)]))
        files.append((spec, Path(ref)))

    vo_source = ELEVENLABS if vo.provider == "elevenlabs" else LOCAL_TTS
    for line, frame in zip(vo.lines, _vo_frames(edit, vo), strict=True):
        spec = SoundSpec(
            kind="vo",
            duration_seconds=line.duration_s,
            params={"line": line.id, "media": line.media_ref},
            provenance=vo_source,
        )
        add(f"vo-{line.id}", "dx", frame, line.media_ref, spec)
    if music is not None:
        bed = SoundSpec(
            kind="music-edit",
            duration_seconds=music.duration_s,
            params={"plan": music.plan_hash, "media": music.media_ref},
            provenance=music.provenance,
        )
        add("music-bed", "mx", 0, music.media_ref, bed)
    by_layer = {(c.cue_id, c.layer_id): c.media_ref for c in design.cues}
    for cue in design.recipe.cues:
        cues.append(cue)
        files += [(layer.sound, Path(by_layer[(cue.id, layer.id)])) for layer in cue.layers]
    return shell.model_copy(update={"cues": cues}), files


def _picture_track(edit: Edit) -> Track | None:
    """The edit's picture: the track named ``picture``, else its first video track."""
    video = [t for t in edit.tracks if t.kind == "video"]
    return next((t for t in video if t.id == "picture"), video[0] if video else None)


def _vo_frames(edit: Edit, vo: VoiceoverTrack) -> list[int]:
    """Edit frame of each VO line: a marker named after its beat, else the n-th clip of
    the edit's ``vo`` track, else straight after the previous line."""
    track = next((t for t in edit.tracks if t.id == "vo"), None)
    clips = [track.record_start(c.id) for c in track.clips()] if track is not None else []
    frames: list[int] = []
    after = 0
    for n, line in enumerate(vo.lines):
        named = [m.frame for m in edit.markers if m.name == line.beat]
        frame = named[0] if len(named) == 1 else clips[n] if n < len(clips) else after
        frames.append(frame)
        after = frame + edit.rate.frames(Fraction(line.duration_s))
    return frames


def _file_selection(spec: SoundSpec, path: Path) -> Selection:
    """A :class:`Selection` that serves ``path`` as ``spec`` to the mix generator."""
    candidate = GeneratedCandidate(0, path, 1.0)
    return Selection("file", spec.kind, spec.provenance.origin, "file", "", (candidate,), 0, spec)


def _duration(path: Path, text: str) -> float:
    """Length of a WAV in seconds; for other formats an estimate from the text."""
    try:
        rate, channels = read_wav(path)
    except (OSError, ValueError):
        return max(0.1, len(text) / _FALLBACK_CHARS_PER_S)
    return max(1, len(channels[0]) if channels else 0) / rate


def _end_card_s(edit: Edit) -> float | None:
    """Where the end card starts (an ``end-card`` marker), in seconds; None when unmarked."""
    for marker in edit.markers:
        if marker.name.lower() in END_CARD_MARKERS:
            return float(edit.rate.seconds(marker.frame))
    return None


def _fit_length(path: Path, seconds: float) -> None:
    """Pad (with silence) or trim ``path`` to exactly ``seconds``."""
    rate, channels = read_wav(path)
    want = round(Fraction(seconds) * rate)
    if channels and len(channels[0]) == want:
        return
    fitted = []
    for chan in channels:
        row = array("f", chan[:want])
        row.extend(array("f", bytes(4 * max(0, want - len(row)))))
        fitted.append(row)
    write_wav(path, fitted, rate, float_format=True)
