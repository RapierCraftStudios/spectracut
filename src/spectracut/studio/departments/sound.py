"""Sound: voiceover, sound design, music and the mix.

- ``voiceover`` (node kind ``voiceover``): voices the script's VO lines. When ElevenLabs
  is configured (``ELEVENLABS_API_KEY`` set, or provider mock mode) it renders final VO;
  otherwise it uses the local TTS model and marks the track ``temp-vo`` so delivery
  flags it (:func:`is_temp_vo`).
- ``sound-designer`` (kind ``sound_design``): a cue for every cut, transition and speed
  ramp of the animatic, each generated by a local model and placed on its edit frame.
  Given a ``picture`` renderer it also adds one foley cue per picture clip with real
  media: the clip is rendered on its own and a video-to-audio model hears it.
- ``composer`` (kind ``music``): a locally generated music bed, cut on bar boundaries to
  the edit's length with its final hit on the end card.
- ``mixer`` (kind ``mix``): renders the DX/MX/FX stems and the master in Ardour and
  checks the master's loudness and true peak for streaming delivery.

All four are built in code by :class:`SoundRunner`; :func:`sound_nodes` declares the
nodes. Nothing here reaches an external service except ElevenLabs for final VO.
Local model time is metered with the runner's clock and recorded as GPU minutes.
"""

