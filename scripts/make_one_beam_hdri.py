"""Generate the One Beam kit's original studio-softbox HDRI (#346).

Writes ``assets/kits/one-beam/hdri/studio-softbox.hdr``, an equirectangular Radiance
RGBE image (run-length encoded scanlines), and its ``.license.json`` sidecar. The
environment is a dark neutral studio: a large warm key softbox, a cooler fill, an
overhead panel and a tall rim strip behind the subject, each with soft edges. Pure
standard library and deterministic: rerunning writes byte-identical files.

Usage: ``uv run python scripts/make_one_beam_hdri.py [OUT_DIR]``.
"""

from __future__ import annotations

import hashlib
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "assets" / "kits" / "one-beam" / "hdri"
NAME = "studio-softbox.hdr"
WIDTH, HEIGHT = 1024, 512

# (azimuth deg, elevation deg, width deg, height deg, softness deg, rgb radiance)
PANELS: tuple[tuple[float, float, float, float, float, tuple[float, float, float]], ...] = (
    (-45.0, 30.0, 44.0, 28.0, 3.0, (14.0, 13.4, 12.6)),  # key softbox, warm neutral
    (120.0, 18.0, 30.0, 18.0, 4.0, (2.6, 2.75, 3.0)),  # fill, cool
    (0.0, 80.0, 70.0, 14.0, 5.0, (3.4, 3.4, 3.4)),  # overhead panel
    (180.0, 28.0, 8.0, 44.0, 1.5, (9.0, 9.6, 10.4)),  # rim strip behind
    (60.0, 12.0, 6.0, 30.0, 1.5, (4.0, 4.0, 4.0)),  # kicker strip
)


def _smooth(edge: float, softness: float, x: float) -> float:
    """1 inside ``|x| <= edge``, smoothly 0 by ``edge + softness``."""
    t = (abs(x) - edge) / softness
    if t <= 0.0:
        return 1.0
    if t >= 1.0:
        return 0.0
    return 1.0 - t * t * (3.0 - 2.0 * t)


def _wrap(deg: float) -> float:
    return (deg + 180.0) % 360.0 - 180.0


def radiance(az: float, el: float) -> tuple[float, float, float]:
    """Scene-linear radiance in direction (azimuth, elevation) in degrees."""
    if el >= 0.0:
        base = 0.03 + 0.02 * (1.0 - el / 90.0)
        rgb = [base * 0.98, base, base * 1.03]
    else:
        g = 0.012 + 0.03 * math.exp(el / 6.0)  # dark floor, brighter towards the horizon
        rgb = [g, g, g]
    for paz, pel, w, h, soft, colour in PANELS:
        k = _smooth(w / 2.0, soft, _wrap(az - paz)) * _smooth(h / 2.0, soft, el - pel)
        if k > 0.0:
            for i in range(3):
                rgb[i] += colour[i] * k
    return rgb[0], rgb[1], rgb[2]


def rgbe(r: float, g: float, b: float) -> bytes:
    v = max(r, g, b)
    if v < 1e-32:
        return b"\x00\x00\x00\x00"
    m, e = math.frexp(v)
    f = m * 256.0 / v
    return bytes((int(r * f), int(g * f), int(b * f), e + 128))


def _rle(channel: bytes) -> bytes:
    """Radiance new-style RLE of one channel of a scanline."""
    out = bytearray()
    i, n = 0, len(channel)
    while i < n:
        run = 1
        while i + run < n and run < 127 and channel[i + run] == channel[i]:
            run += 1
        if run >= 4:
            out += bytes((128 + run, channel[i]))
            i += run
            continue
        start = i
        while i < n and i - start < 128:
            ahead = 1
            while i + ahead < n and ahead < 4 and channel[i + ahead] == channel[i]:
                ahead += 1
            if ahead >= 4:
                break
            i += 1
        out += bytes((i - start,)) + channel[start:i]
    return bytes(out)


def encode(width: int, height: int) -> bytes:
    header = f"#?RADIANCE\nFORMAT=32-bit_rle_rgbe\n\n-Y {height} +X {width}\n".encode()
    body = bytearray(header)
    for y in range(height):
        el = 90.0 - (y + 0.5) * 180.0 / height
        line = [
            rgbe(*radiance((x + 0.5) * 360.0 / width - 180.0, el)) for x in range(width)
        ]
        body += bytes((2, 2, width >> 8, width & 0xFF))
        for c in range(4):
            body += _rle(bytes(px[c] for px in line))
    return bytes(body)


def main(out_dir: Path = OUT_DIR) -> str:
    out_dir.mkdir(parents=True, exist_ok=True)
    data = encode(WIDTH, HEIGHT)
    path = out_dir / NAME
    path.write_bytes(data)
    sha = hashlib.sha256(data).hexdigest()
    sidecar = {
        "sha256": sha,
        "license": {
            "source": "SpectraCut",
            "licence": "CC0-1.0",
            "attribution": "Original studio-softbox HDRI generated by scripts/make_one_beam_hdri.py",
            "non_commercial": False,
            "commercial_safe": True,
        },
    }
    (out_dir / f"{NAME}.license.json").write_text(
        json.dumps(sidecar, indent=2) + "\n", encoding="utf-8"
    )
    return sha


if __name__ == "__main__":
    print(main(Path(sys.argv[1]) if len(sys.argv) > 1 else OUT_DIR))
